import json
import os
from typing import Any, Dict

CONFIG_FILE = "config_models_keys.json"
INTERNAL_RAG_DB = "internal_dynamic_rag.db"
LOCAL_GLOSSARY_DB = "local_glossary.db"
LOCAL_CHARACTERS_DB = "local_characters.db"
def load_persistent_config() -> Dict[str, Any]:
    # Defaults completos (inclui idioma + gdrive). Arquivos antigos
    # podem nao ter essas chaves -> faz merge em vez de ignorar.
    # Tambem nunca apaga chaves de API ja salvas.
    default_api_keys = {
        "openai": "",
        "openrouter": "",
        "deepseek": "",
        "gemini": "",
        "mistral": "",
        "nvidia": "",
        "groq": "",
        "grok": ""
    }
    default_gdrive = {
        "credentials_json_path": "credentials.json",
        "glossary_link_or_id": "",
        "characters_link_or_id": ""
    }
    # Descrição de como cada base (planilha) está organizada — ver base_schema.py.
    # base_descriptions[kind][hash_dos_cabecalhos] = {text, origin, updated_at, label}
    default_base_desc = {"glossary": {}, "characters": {}}
    default_schema_llm = {"provider": "", "model": ""}
    default_models = {
        "openai": ["gpt-4o", "gpt-4o-mini", "gpt-4-turbo"],
        "openrouter": ["anthropic/claude-3.5-sonnet", "google/gemini-pro-1.5", "meta-llama/llama-3-70b-instruct"],
        "deepseek": ["deepseek-chat", "deepseek-coder"],
        # gemini-1.5-* foi removido da API (HTTP 404); usar 2.5+.
        "gemini": ["gemini-2.5-flash", "gemini-2.5-pro"],
        "mistral": ["mistral-large-latest", "mistral-medium"],
        "nvidia": ["nvidia/llama-3.1-nemotron-70b-instruct"],
        "groq": ["llama-3.3-70b-versatile", "mixtral-8x7b-32768"],
        "grok": ["grok-beta"],
        "ollama": ["llama3", "llama3.1", "mistral", "gemma2", "phi3"]
    }
    default_config: Dict[str, Any] = {
        "interface_language": "Português",
        "api_keys": dict(default_api_keys),
        "gdrive_config": dict(default_gdrive),
        "custom_models": {k: list(v) for k, v in default_models.items()},
        "base_descriptions": {k: dict(v) for k, v in default_base_desc.items()},
        "base_schema_llm": dict(default_schema_llm),
    }
    if os.path.exists(CONFIG_FILE):
        try:
            with open(CONFIG_FILE, "r", encoding="utf-8") as f:
                loaded = json.load(f)
            if isinstance(loaded, dict):
                merged: Dict[str, Any] = dict(default_config)
                merged.update(loaded)
                # merge raso para sub-dicts (preserva chaves novas sem apagar salvas)
                api = dict(default_api_keys)
                if isinstance(loaded.get("api_keys"), dict):
                    api.update(loaded["api_keys"])
                merged["api_keys"] = api
                gd = dict(default_gdrive)
                if isinstance(loaded.get("gdrive_config"), dict):
                    gd.update(loaded["gdrive_config"])
                merged["gdrive_config"] = gd
                cm = {k: list(v) for k, v in default_models.items()}
                if isinstance(loaded.get("custom_models"), dict):
                    for k, v in loaded["custom_models"].items():
                        cm[k] = v
                merged["custom_models"] = cm
                # base_descriptions: merge por base (preserva descrições já salvas).
                bd = {k: dict(v) for k, v in default_base_desc.items()}
                if isinstance(loaded.get("base_descriptions"), dict):
                    for k in default_base_desc:
                        if isinstance(loaded["base_descriptions"].get(k), dict):
                            bd[k] = loaded["base_descriptions"][k]
                merged["base_descriptions"] = bd
                bsl = dict(default_schema_llm)
                if isinstance(loaded.get("base_schema_llm"), dict):
                    bsl.update(loaded["base_schema_llm"])
                merged["base_schema_llm"] = bsl
                if not merged.get("interface_language"):
                    merged["interface_language"] = "Português"
                return merged
        except Exception:
            pass
    save_persistent_config(default_config)
    return default_config

def save_persistent_config(config_data: Dict[str, Any]):
    with open(CONFIG_FILE, "w", encoding="utf-8") as f:
        json.dump(config_data, f, indent=4, ensure_ascii=False)



